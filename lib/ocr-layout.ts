/**
 * ocr-layout.ts — スコアカード「Stroke Gained Putting v2」の物理レイアウト。
 *
 * scorecard-v2.html をヘッドレスブラウザで描画して計測した値（自動生成。手で編集しない）。
 * 座標は四隅の■マーク中心を基準にした正規化座標:
 *   TL マーク中心 = (0, 0)、TR = (1, 0)、BL = (0, 1)、BR = (1, 1)
 *   x は「マーク矩形の幅」、y は「マーク矩形の高さ」を 1 とする単位。
 * カードのレイアウトを変えたら scratchpad の measure.js を再実行して更新すること。
 */

export type NormRect = { x: number; y: number; w: number; h: number };

export type SectionLayout = {
  /** In（カップイン）チェック枠 */
  cupIn: NormRect;
  /** Putt/Result 5枠: E, Ba, P, Bo, D+ */
  result: NormRect[];
  /** Length 2枠（十の位・一の位） */
  length: NormRect[];
  /** Line(U/D) 3枠: F, U, D */
  lineUD: NormRect[];
  /** Line(L/R) 3枠: St, L, R */
  lineLR: NormRect[];
};

export type ScorecardLayout = {
  /** マーク中心矩形の 高さ / 幅 */
  markerRectAspect: number;
  /** マーク1辺の長さ（マーク矩形幅を1とした値） */
  markerSizeNorm: number;
  /** カード用紙の外形（切り取り線）。補正画像の出力範囲に使う */
  cardBounds: NormRect;
  header: {
    hole: NormRect[];
    date: NormRect[];
    course: NormRect;
  };
  /** 1st, 2nd, 3rd Putt の順 */
  sections: [SectionLayout, SectionLayout, SectionLayout];
};

